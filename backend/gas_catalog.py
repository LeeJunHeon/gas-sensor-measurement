"""
gas_catalog.py — 가스 변환계수(C.F.) 표.

열식 MFC(HORIBA S48)는 전 채널 N2 로 교정되어 출고된다. 다른 기체를 흘리면
지시값과 실제 유량이 달라지므로 매뉴얼의 변환계수로 보정한다.

  매뉴얼 CONVERSION FACTOR 절:
      실제 유량 = 설정 유량 ÷ (교정가스 C.F.) × (사용가스 C.F.)
  교정가스가 N2(C.F.=1.000)이므로 이 장비에서는
      실제 유량 = 지시 유량 × (사용가스 C.F.)
      지시(SV) 유량 = 목표 유량 ÷ (사용가스 C.F.)

★ 출처: HORIBA S48(M)-BR/BM 매뉴얼 CONVERSION FACTOR 표 (N2 교정 기준).
  표에 없는 가스는 호리바에 문의할 것 — 타사 표를 섞어 쓰지 않는다
  (제조사마다 기준 온도·환산식이 달라 값이 어긋난다).
★ 매뉴얼 예시 1의 "H2 → 1.4" 문장은 같은 매뉴얼의 표(H2 = 1.012)와 모순된다.
  표를 준거로 삼고 예시는 오타로 간주한다.
"""

GAS_CF = [
    ("Air", 1.000), ("Ar", 1.418), ("CF4", 0.427), ("CH4", 0.753), ("CHF3", 0.511),
    ("C2H4", 0.589), ("C2H6", 0.500), ("C2F6", 0.248), ("C3H6", 0.410), ("C3H8", 0.343),
    ("i-C4H8", 0.300), ("n-C4H10", 0.260), ("i-C4H10", 0.260), ("CO", 1.000), ("CO2", 0.735),
    ("Cl2", 0.838), ("H2", 1.012), ("HCl", 0.994), ("He", 1.415), ("Kr", 1.370),
    ("N2", 1.000), ("NF3", 0.510), ("NO", 0.990), ("N2O", 0.709), ("Ne", 1.413),
    ("O2", 0.980), ("SiH4", 0.602), ("SF6", 0.266), ("SO2", 0.683), ("Xe", 1.363),
]

DEFAULT_GAS_NAME = "N2"     # 교정가스. 이 값에서는 보정이 항등이라 기존 동작과 동일하다.
DEFAULT_GAS_CF = 1.000

# C.F. 허용 범위. 표의 최소·최대(0.248~1.418)보다 넉넉히 두되, 오타(0·음수·100배)는 막는다.
CF_MIN, CF_MAX = 0.1, 10.0

_BY_NAME = {n: v for n, v in GAS_CF}


def cf_of(name: str):
    """표에 있는 기체면 C.F., 없으면 None(직접 입력 값이라는 뜻)."""
    return _BY_NAME.get(name)


def clamp_cf(v, dflt: float = DEFAULT_GAS_CF) -> float:
    """C.F. 정규화. 숫자가 아니거나 허용 범위 밖이면 기본값(1.000)으로 되돌린다 —
    0 이나 음수를 그대로 두면 나눗셈에서 유량이 발산하거나 부호가 뒤집힌다."""
    try:
        f = float(v)
    except (TypeError, ValueError):
        return dflt
    if not (CF_MIN <= f <= CF_MAX):
        return dflt
    return f


def catalog() -> list:
    """스냅샷용 [{"name":..., "cf":...}] — 프런트 드롭다운의 단일 출처."""
    return [{"name": n, "cf": v} for n, v in GAS_CF]
